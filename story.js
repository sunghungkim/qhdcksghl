function buildStory() {
  const mk = (tag, cls, text) => {
    const e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text; // textContent 만 사용
    return e;
  };
  const story = mk('section', 'story');
  story.setAttribute('aria-labelledby', 'story-title');

  // 제목
  const head = mk('div', 'story-head');
  const h = mk('h2', 'story-title', '봉찬회에 대하여 (역사)'); h.id = 'story-title';
  head.append(h, mk('p', 'story-sub', '불교 성지순례 봉찬회(奉讚會)'));
  story.append(head);

  // 바로가기: 길어서 원하는 부분으로 바로 이동
  const parts = [];
  const part = (id, title) => {
    const s = mk('section', 'story-part'); s.id = id;
    s.append(mk('h3', 'story-h3', title));
    parts.push([id, title, s]); return s;
  };

  // 1) 연혁
  const sHist = part('story-history', '연혁');
  const ol = mk('ol', 'timeline');
  STORY_HISTORY.forEach(([year, what]) => {
    const li = mk('li');
    li.append(mk('span', 'tl-year', year), mk('span', 'tl-what', what));
    ol.append(li);
  });
  sHist.append(ol);

  // 2) 의미
  const sMean = part('story-meaning', '봉찬회의 의미');
  const row = mk('div', 'hanja-row');
  STORY_HANJA.forEach(([ch, read]) => {
    const c = mk('div', 'hanja');
    c.append(mk('div', 'hanja-ch', ch), mk('div', 'hanja-read', read));
    row.append(c);
  });
  sMean.append(row, mk('p', 'prose', STORY_MEANING));

  // 3) 시작과 하는 일
  const sWork = part('story-work', '봉찬회의 시작과 하는 일');
  STORY_WORK.forEach((t) => sWork.append(mk('p', 'prose', t)));

  // 4) 봉찬회에 대하여
  const sAbout = part('story-about', '봉찬회 이야기');
  STORY_ABOUT.forEach(([title, paras]) => {
    sAbout.append(mk('h4', 'story-h4', title));
    paras.forEach((t) => sAbout.append(mk('p', 'prose', t)));
  });

  const nav = mk('nav', 'story-nav'); nav.setAttribute('aria-label', '봉찬회 이야기 바로가기');
  [['story-history', '연혁'], ['story-meaning', '의미'], ['story-work', '시작과 하는 일'], ['story-about', '봉찬회 이야기']].forEach(([id, label]) => {
    const b = mk('button', 'btn ghost small', label); b.type = 'button';
    b.addEventListener('click', () => { const t = story.querySelector('#' + id); if (t) t.scrollIntoView({ block: 'start' }); });
    nav.append(b);
  });
  story.append(nav);
  parts.forEach(([, , s]) => story.append(s));
  return story;
}
